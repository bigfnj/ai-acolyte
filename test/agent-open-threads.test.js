'use strict';

// The open-threads block (src/agent-open-threads.js, 2026-10-19). It shares agent-guidance.js's
// block and target plumbing with the shell-style and gates blocks and nothing else, so what is
// tested here is its own contract: one read of the compiled file, the bytes checked are the bytes
// installed, a missing compile is nothing to do, an unreadable or torn one is refused with every
// instruction file left as it was, a compile with nothing open removes the block from every
// agent, and turning it off never touches the gates or the shell-style block.

const test = require('node:test');
const { after } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { removeDir } = require('./helpers/remove-dir');

const { applyGuidance } = require('../src/agent-guidance');
const { makeGatesBlock, compiledPath: gatesPath } = require('../src/agent-gates');
const {
  THREADS_BEGIN, THREADS_END, compiledPath, openThreadsStatusAll, setOpenThreadsAll,
} = require('../src/agent-open-threads');

const USER_TEXT = '# My global instructions\n\nKeep this.\n';
const CODEX_TEXT = '# Codex instructions\n';

// A compiled file exactly as recall.py _compile_threads_text writes it: the header with the sha
// of every byte below it, the heading, the INDEX line when given, then the thread lines.
function compiled({ threads = [], index = null, count = threads.length } = {}) {
  const lines = [...(index ? [`- **INDEX** ${index}`] : []), ...threads];
  const body = `## Open threads (${count}, managed)\n${lines.map((line) => `${line}\n`).join('')}`;
  const sha = crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16);
  return `<!-- generated by recall.py --threads-compile; sha ${sha} -->\n${body}`;
}
const ONE = compiled({ threads: ['- **AWAITING** The owner decides the layout. (project_layout)'] });
const INDEX_TEXT = 'MEMORY.md is 152 lines (budget 140): compact it before adding anything, and move detail into the memory files.';

const roots = [];
after(async () => {
  for (const root of roots) {
    try { await removeDir(root); } catch { /* never fail the suite */ }
  }
});

// A home with CLAUDE.md and Codex's AGENTS.md holding the user's own text, and `text` as the
// compiled file (null for none).
function home(text = ONE, { codex = true } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'acolyte-threads-'));
  roots.push(root);
  fs.mkdirSync(path.join(root, '.claude'), { recursive: true });
  fs.writeFileSync(path.join(root, '.claude', 'CLAUDE.md'), USER_TEXT);
  if (codex) {
    fs.mkdirSync(path.join(root, '.codex'), { recursive: true });
    fs.writeFileSync(path.join(root, '.codex', 'AGENTS.md'), CODEX_TEXT);
  }
  if (text !== null) fs.writeFileSync(compiledPath(root), text);
  return {
    root,
    claude: () => fs.readFileSync(path.join(root, '.claude', 'CLAUDE.md'), 'utf8'),
    codex: () => fs.readFileSync(path.join(root, '.codex', 'AGENTS.md'), 'utf8'),
    backups: () => (fs.existsSync(path.join(root, '.claude', 'backups')) ? fs.readdirSync(path.join(root, '.claude', 'backups')).sort() : []),
  };
}

// Every read of open-threads.generated.md, counted, answered by `answer(n, real)`.
function countReads(t, root, answer = (n, real) => real()) {
  const realRead = fs.readFileSync;
  const seen = { reads: 0 };
  t.mock.method(fs, 'readFileSync', (target, ...rest) => {
    if (path.resolve(String(target)) !== path.resolve(compiledPath(root))) return realRead(target, ...rest);
    seen.reads += 1;
    return answer(seen.reads, () => realRead(target, ...rest));
  });
  return seen;
}

test('the markers and the compiled path are the documented ones', () => {
  // docs/acolyte-rename-migration.md lists every managed-block marker: a rename that touched
  // these would strand every block already installed.
  assert.equal(THREADS_BEGIN, '<!-- BEGIN permission-wildcarding: open threads (managed) -->');
  assert.equal(THREADS_END, '<!-- END permission-wildcarding: open threads -->');
  assert.equal(compiledPath('/h'), path.join('/h', '.claude', 'open-threads.generated.md'));
});

test('a whole compile installs into every agent, reads current, and off is a byte-for-byte round trip', () => {
  const h = home();
  const rows = setOpenThreadsAll(true, { home: h.root });
  assert.deepEqual(rows.map((row) => [row.agent, row.changed, row.on, row.error, row.threads, row.index]),
    [['claude', true, true, null, 1, null], ['codex', true, true, null, 1, null]]);
  for (const text of [h.claude(), h.codex()]) {
    assert.ok(text.includes(`${THREADS_BEGIN}\n${ONE.trim()}\n${THREADS_END}\n`), 'the compiled text is the block body, whole');
  }
  assert.ok(h.claude().startsWith(USER_TEXT), 'the user text keeps its place at the top');
  const status = openThreadsStatusAll({ home: h.root });
  assert.deepEqual(status.map((row) => [row.agent, row.on, row.current, row.compile, row.threads, row.wanted]),
    [['claude', true, true, 'whole', 1, true], ['codex', true, true, 'whole', 1, true]]);
  assert.deepEqual(setOpenThreadsAll(true, { home: h.root }).map((row) => row.changed), [false, false], 'a second on writes nothing');
  assert.deepEqual(h.backups(), ['AGENTS.md.pre-open-threads', 'AGENTS.md.pre-open-threads-prev',
    'CLAUDE.md.pre-open-threads', 'CLAUDE.md.pre-open-threads-prev'], 'its own backup names, never the gates\' or guidance\'s');

  setOpenThreadsAll(false, { home: h.root });
  assert.equal(h.claude(), USER_TEXT);
  assert.equal(h.codex(), CODEX_TEXT);
  assert.deepEqual(openThreadsStatusAll({ home: h.root }).map((row) => row.on), [false, false]);
});

test('the compiled file is read once per install and once per status, and those bytes are installed', (t) => {
  // A writer replacing the file between two reads would otherwise pair one check with another
  // file's bytes. Every read after the first here sees a different compile.
  const h = home();
  const other = compiled({ threads: ['- **OPEN** A different compile. (other)'] });
  const seen = countReads(t, h.root, (n, real) => (n === 1 ? real() : other));
  const rows = setOpenThreadsAll(true, { home: h.root });
  assert.equal(seen.reads, 1, 'one read of the compiled file for the whole install');
  assert.ok(rows.every((row) => row.error === null));
  assert.ok(h.claude().includes('The owner decides the layout.') && !h.claude().includes('A different compile.'));
  seen.reads = 0;
  openThreadsStatusAll({ home: h.root });
  assert.equal(seen.reads, 1, 'one read for a status');
  // MUTATION: read the compiled file again inside makeThreadsBlock (a late-reading body) and
  // both counts fail, and the install carries the other compile.
});

test('a missing compile is nothing to do: no write, no backup, and no error', () => {
  const h = home(null);
  const rows = setOpenThreadsAll(true, { home: h.root });
  assert.equal(rows.length, 1);
  assert.equal(rows[0].refusal, 'missing');
  assert.equal(rows[0].error, null, 'an unattended caller logs nothing for it');
  assert.equal(h.claude(), USER_TEXT);
  assert.equal(h.codex(), CODEX_TEXT);
  assert.deepEqual(h.backups(), []);
  assert.deepEqual(openThreadsStatusAll({ home: h.root }).map((row) => row.compile), ['missing', 'missing']);
  // MUTATION: treat ENOENT as an empty read in readCompiled and the row is `torn`, with an error.
});

test('an unreadable compile is refused, and the installed block stays resident', (t) => {
  const h = home();
  setOpenThreadsAll(true, { home: h.root });
  const before = { claude: h.claude(), codex: h.codex() };
  countReads(t, h.root, () => { throw Object.assign(new Error('EBUSY: resource busy or locked'), { code: 'EBUSY' }); });
  const [row] = setOpenThreadsAll(true, { home: h.root });
  assert.equal(row.refusal, 'unreadable');
  assert.match(row.error, /cannot read .*open-threads\.generated\.md \(EBUSY\): nothing was written/);
  assert.deepEqual({ claude: h.claude(), codex: h.codex() }, before);
  assert.deepEqual(openThreadsStatusAll({ home: h.root }).map((row) => [row.compile, row.refusal]),
    [['refused', 'unreadable'], ['refused', 'unreadable']]);
  // Off needs no compile at all.
  assert.ok(setOpenThreadsAll(false, { home: h.root }).every((r) => r.error === null));
  assert.equal(h.claude(), USER_TEXT);
});

test('a torn or hand-edited compile is refused for every agent, with every file left as it was', () => {
  const h = home();
  setOpenThreadsAll(true, { home: h.root });
  const before = { claude: h.claude(), codex: h.codex(), backups: h.backups() };
  const header = ONE.slice(0, ONE.indexOf('\n') + 1);
  const cases = {
    'an empty file': '',
    'a read torn inside the header': ONE.slice(0, 20),
    'a read torn at the end of the header': header,
    'a read torn mid-body': ONE.slice(0, ONE.length - 10),
    'an editor\'s extra newline': `${ONE}\n`,
    'a hand edit': ONE.replace('owner', 'agent'),
    'CRLF line endings': ONE.replace(/\n/g, '\r\n'),
    'a byte-order mark': `${String.fromCharCode(0xfeff)}${ONE}`,
    'no heading under a valid sha': (() => {
      const body = '- **OPEN** No heading. (x)\n';
      return `<!-- generated by recall.py --threads-compile; sha ${crypto.createHash('sha256').update(body).digest('hex').slice(0, 16)} -->\n${body}`;
    })(),
    'a gates compile in its place': '<!-- generated by recall.py --gates-compile; sha 0123456789abcdef -->\n## Standing gates (1 memories, managed)\n\n- x\n',
  };
  for (const [name, text] of Object.entries(cases)) {
    fs.writeFileSync(compiledPath(h.root), text);
    const rows = setOpenThreadsAll(true, { home: h.root });
    assert.equal(rows.length, 1, name);
    assert.equal(rows[0].refusal, 'torn', name);
    assert.match(rows[0].error, /open-threads\.generated\.md .*: nothing was written; recompile with `wildcard-perms --open-threads refresh`/, name);
    assert.deepEqual({ claude: h.claude(), codex: h.codex(), backups: h.backups() }, before, `${name}: nothing was written`);
  }
  // MUTATION: drop the sha comparison in readCompiled and the hand edit, the torn body and the
  // extra newline install; drop the HEADING check and the headingless file installs.
});

test('a whole compile with nothing open removes the block from every agent, and the user text is whole', () => {
  const h = home();
  setOpenThreadsAll(true, { home: h.root });
  assert.ok(h.claude().includes(THREADS_BEGIN) && h.codex().includes(THREADS_BEGIN), 'precondition: installed');
  fs.writeFileSync(compiledPath(h.root), compiled({ threads: [] }));
  const rows = setOpenThreadsAll(true, { home: h.root });
  assert.deepEqual(rows.map((row) => [row.agent, row.changed, row.on, row.error, row.wanted]),
    [['claude', true, false, null, false], ['codex', true, false, null, false]]);
  assert.equal(h.claude(), USER_TEXT);
  assert.equal(h.codex(), CODEX_TEXT);
  const status = openThreadsStatusAll({ home: h.root });
  assert.deepEqual(status.map((row) => [row.on, row.current, row.wanted, row.threads]), [[false, true, false, 0], [false, true, false, 0]],
    'a compile that wants no block is current once none is left');
  // And a header-only compile on a clean file writes nothing at all.
  assert.deepEqual(setOpenThreadsAll(true, { home: h.root }).map((row) => row.changed), [false, false]);
  // MUTATION: install whenever the compile is whole (setGuidanceAll(true, ...)) and the
  // header-only block is written instead of removed; drop the `current` override in
  // openThreadsStatusAll and status reads stale forever.
});

test('an INDEX line with no thread still installs, and status carries its text', () => {
  const h = home(compiled({ threads: [], index: INDEX_TEXT }));
  const rows = setOpenThreadsAll(true, { home: h.root });
  assert.deepEqual(rows.map((row) => [row.on, row.threads, row.index]), [[true, 0, INDEX_TEXT], [true, 0, INDEX_TEXT]]);
  assert.ok(h.claude().includes(`- **INDEX** ${INDEX_TEXT}`));
  assert.deepEqual(openThreadsStatusAll({ home: h.root }).map((row) => [row.index, row.wanted, row.current]),
    [[INDEX_TEXT, true, true], [INDEX_TEXT, true, true]]);
  // An INDEX-like line that is not the first line under the heading is a thread's text, not the index.
  fs.writeFileSync(compiledPath(h.root), compiled({ threads: ['- **OPEN** x (a)', `- **INDEX** ${INDEX_TEXT}`] }));
  assert.equal(openThreadsStatusAll({ home: h.root })[0].index, null);
  // MUTATION: wanted = count > 0 (the INDEX line ignored) and the first install removes instead.
});

test('Codex\'s nonempty AGENTS.override.md is the file that gets the block', () => {
  const h = home();
  const override = path.join(h.root, '.codex', 'AGENTS.override.md');
  fs.writeFileSync(override, '# Override\n');
  const codex = setOpenThreadsAll(true, { home: h.root }).find((row) => row.agent === 'codex');
  assert.equal(codex.path, override);
  assert.ok(fs.readFileSync(override, 'utf8').includes(THREADS_BEGIN));
  assert.equal(h.codex(), CODEX_TEXT, 'the shadowed AGENTS.md is untouched');
  setOpenThreadsAll(false, { home: h.root });
  assert.equal(fs.readFileSync(override, 'utf8'), '# Override\n');
});

test('only agents that are installed are written, and none is conjured', () => {
  const h = home(ONE, { codex: false });
  const rows = setOpenThreadsAll(true, { home: h.root });
  assert.deepEqual(rows.map((row) => row.agent), ['claude']);
  assert.equal(fs.existsSync(path.join(h.root, '.codex')), false);
});

test('the open-threads block, the gates block and the shell-style block never touch each other', () => {
  const h = home();
  fs.writeFileSync(gatesPath(h.root), '## Standing gates (1 memories, managed)\n\n- **A gate.** Keep it.\n');
  const claudeFile = path.join(h.root, '.claude', 'CLAUDE.md');
  const withOthers = makeGatesBlock(h.root).apply(applyGuidance(USER_TEXT, true).text, true).text;
  fs.writeFileSync(claudeFile, withOthers);
  setOpenThreadsAll(true, { home: h.root });
  assert.ok(h.claude().startsWith(withOthers.trimEnd()), 'both other blocks are kept byte for byte');
  setOpenThreadsAll(false, { home: h.root });
  assert.equal(h.claude(), withOthers, 'off takes the open-threads block and nothing else');
  // The other way round: the gates block coming off leaves the open-threads block whole.
  setOpenThreadsAll(true, { home: h.root });
  const installed = h.claude();
  const block = installed.slice(installed.indexOf(THREADS_BEGIN));
  fs.writeFileSync(claudeFile, makeGatesBlock(h.root).apply(installed, false).text);
  assert.ok(h.claude().endsWith(block), 'gates off leaves the open-threads block whole');
});

test('inPlaceFallback: false leaves a held instruction file untouched', (t) => {
  const h = home();
  const claudeFile = path.join(h.root, '.claude', 'CLAUDE.md');
  const realRename = fs.renameSync;
  t.mock.method(fs, 'renameSync', (from, to) => {
    if (path.resolve(String(to)) === path.resolve(claudeFile)) {
      throw Object.assign(new Error(`EPERM: operation not permitted, rename '${from}' -> '${to}'`), { code: 'EPERM' });
    }
    return realRename(from, to);
  });
  t.mock.method(process, 'emitWarning', () => {});
  const rows = setOpenThreadsAll(true, { home: h.root, inPlaceFallback: false });
  const claude = rows.find((row) => row.agent === 'claude');
  assert.match(claude.error, /rename attempts/);
  assert.equal(h.claude(), USER_TEXT, 'the held CLAUDE.md keeps every byte');
  assert.ok(h.codex().includes(THREADS_BEGIN), 'and the other agent is still installed');
  // MUTATION: drop `...options` from setOpenThreadsAll's setGuidanceAll call and the held file is
  // rewritten in place.
});
