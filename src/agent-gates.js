'use strict';

// Compiled memory gates — make the standing orders resident.
//
// `agent-guidance.js` installs a block whose text is a const in this repo. This one
// installs a block whose text is derived from the user's own memory corpus:
// `recall.py --gates-compile` lifts the `<!-- gate -->` ... `<!-- /gate -->` section out of
// every memory whose frontmatter says `scope: global`, and concatenates them into
// gates.generated.md. Selection is on `scope: global` alone: `type:` plays no part, so a
// `reference` with a paired block compiles exactly like a `feedback` (recall.py
// _compile_gates_text, "Selected on scope, not type"). This said `type: feedback` +
// `scope: global` until 2026-10-14, long after the selection stopped reading `type:`.
// Only one memory store compiles: memory.dir when the user sets it, else the store with
// the most memory files. Gate memories in any other store are reported, never compiled.
//
// Why bother, when the memory index already exists: the index is a list of *hooks*, and
// the enforceable half of a rule lives in the file body, which only loads if a recall
// happens to surface it. That works for reference material and fails for standing orders,
// because you cannot recall a rule you are already breaking — nothing triggers the lookup.
// So policy has to be resident and facts do not, and the index currently mixes them.
//
// Why an instruction file rather than a hook: a SessionStart hook is the obvious way to
// force text into every session, and it is unavailable under a managed policy that sets
// allowManagedHooksOnly. Instruction-file text is the one always-loaded surface that
// survives, which is why this ships as a managed block.
//
// Separate markers from the shell-style block on purpose. The two have different
// lifecycles — one is release-versioned, one tracks a corpus that changes underneath it —
// and independent switches, so `--guidance off` must never take the gates with it.

const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const {
  createManagedBlock, guidanceStatusAll, setGuidanceAll,
} = require('./agent-guidance');

const GATES_BEGIN = '<!-- BEGIN permission-wildcarding: memory gates (managed) -->';
const GATES_END = '<!-- END permission-wildcarding: memory gates -->';

// Where recall.py --gates-compile writes. Alongside the file it feeds rather than in a
// checkout: it is derived from a private memory dir and has no business being committed.
function compiledPath(home = os.homedir()) {
  return path.join(home, '.claude', 'gates.generated.md');
}

// Read late, on every call, so a recompile is picked up without reloading the extension.
// Empty string for "not compiled yet", null for a real read error.
function readCompiled(home = os.homedir()) {
  try { return fs.readFileSync(compiledPath(home), 'utf8').trim(); }
  catch (error) { return error.code === 'ENOENT' ? '' : null; }
}

// recall.py heads every compile with the first 16 hex digits of the SHA-256 of the gates
// below the count line (recall.py _compile_gates_text). readCompiled trims the final
// newline, which is not part of what was hashed.
const COMPILED_HEADER = /^<!-- generated by recall\.py --gates-compile; sha ([0-9a-f]{16}) -->\n## Standing gates \(\d+ memories, managed\)\n\n/;

// Whether a compiled text is the whole of what recall.py wrote (ported from rampage
// 7139659). A compile written in place (open, truncate, write), as recall.py did until
// 2026-10-14 and an older checkout still does, can be read mid-write and return a prefix,
// and a prefix is a truncated gate set that installed without complaint. Its gates then no
// longer hash to the sha in its own header. A text with no header (an older compile, or a
// hand-made one) has nothing to check against and is taken as it is.
//
// "No header" has to mean the text never started one. A read torn INSIDE the header line
// (`<!-- generated by recall.py --gates-comp`) matches no header either, and would be taken
// as a headerless compile and installed over the user's gates. So a text that begins the way
// recall.py's header begins, or is a shorter piece of that beginning, must match it in full.
const HEADER_START = '<!-- generated by recall.py';

function compiledIsWhole(compiled) {
  const header = COMPILED_HEADER.exec(compiled);
  if (!header) return !(compiled.startsWith(HEADER_START) || HEADER_START.startsWith(compiled));
  const gates = compiled.slice(header[0].length);
  return crypto.createHash('sha256').update(gates, 'utf8').digest('hex').slice(0, 16) === header[1];
}

// The body is the compiled file, so staleness needs no version bump: edit a memory,
// recompile, and isCurrent() goes false on its own because the bytes differ.
//
// Bound to a home rather than closing over os.homedir(): every caller here already takes
// a home, and a block that read the default one would check a caller's compile and then
// install somebody else's bytes.
//
// `compiled`, when given, is the body, fixed: a caller that has already read and checked
// the compiled text installs exactly those bytes. Without it the body is read late, on
// every use, and two uses can see two different files.
function makeGatesBlock(home = os.homedir(), compiled) {
  return createManagedBlock({
    begin: GATES_BEGIN,
    end: GATES_END,
    body: typeof compiled === 'string' ? compiled : () => readCompiled(home) || '',
  });
}

// Deliberately NOT a module-level `makeGatesBlock()` singleton. Every entry point here takes
// a home, and a block built at require time would freeze whatever os.homedir() said then --
// which is how a test with a mocked home ends up writing to the real ~/.claude.

// The compiled file is read once, so `compiled` and `current` describe the same bytes.
function gatesStatusAll(homeOrOptions) {
  const options = typeof homeOrOptions === 'string' ? { home: homeOrOptions } : (homeOrOptions || {});
  const home = options.home ?? os.homedir();
  const text = readCompiled(home);
  const compiled = !!text;
  return guidanceStatusAll(options, makeGatesBlock(home, text || '')).map((state) => ({ ...state, compiled }));
}

// Why an install would be refused, or null. Every one of these leaves every instruction
// file exactly as it was. `kind` and the bare `reason` travel on the refused row beside
// the full `error`, because `wildcard-perms --gates refresh` IS the advice two of these
// give, and it words the outcome itself rather than telling a hook to run itself.
function refusalFor(compiled, home) {
  // An empty block: without this, a missing compile would fence off nothing, report
  // success, and leave a card reading "gates ON" forever, the exact silent-failure shape
  // this whole feature exists to avoid.
  if (compiled === '') {
    return { kind: 'empty', reason: 'no compiled gates',
      error: 'no compiled gates: run `recall.py --gates-compile` first (`wildcard-perms --gates refresh` compiles and installs)' };
  }
  // A read that failed outright. A writer holding the file open reads as EBUSY on Windows,
  // and the late-reading body's `|| ''` turned it into an empty block past the check above.
  if (compiled === null) {
    const reason = `cannot read ${compiledPath(home)}: nothing was written`;
    return { kind: 'unreadable', reason, error: `${reason}, try again` };
  }
  if (!compiledIsWhole(compiled)) {
    const reason = `${compiledPath(home)} does not match the sha in its own header (read while it was being `
      + 'written, or edited by hand): nothing was written';
    return { kind: 'torn', reason, error: `${reason}; recompile with \`wildcard-perms --gates refresh\`` };
  }
  return null;
}

function setGatesAll(on, options = {}) {
  const home = options.home ?? os.homedir();
  // Read ONCE, and the block is built from that string, so the bytes checked here are the
  // bytes written. The block used to re-read the file on every use (each isCurrent and
  // apply call), after this check had passed. Rampage measured it against a writer
  // rewriting the file the way recall.py then did: 23 of 38 first-time migrations replaced
  // the user's full gates with an empty block and reported success (7139659).
  const compiled = readCompiled(home);
  const refusal = on ? refusalFor(compiled, home) : null;
  if (refusal) {
    return [{
      agent: 'all', changed: false, path: compiledPath(home), on: false, compiled: false,
      error: refusal.error, refusal: refusal.kind, reason: refusal.reason,
    }];
  }
  // Share discovery, override migration and removal with the shell block. The
  // distinct backup suffix keeps the two features' pre-change copies separate. `off`
  // needs no body (removal reads the markers), so it goes ahead whatever the file holds.
  return setGuidanceAll(on, { ...options, block: makeGatesBlock(home, compiled || ''), backupSuffix: 'pre-gates' });
}

module.exports = {
  GATES_BEGIN, GATES_END, makeGatesBlock,
  compiledPath, readCompiled, gatesStatusAll, setGatesAll,
};
