'use strict';

// Open threads: the memories whose `status:` says something is still open, made resident
// (2026-10-19).
//
// MEMORY.md is the one memory file Claude Code loads every session, and only its first 200
// lines. It bloated because agents wrote STATUS on its index lines: 10 of the 15 lines demoted
// from the owner's index carried DONE, SHIPPED or AWAITING. Status now has a home of its own. A
// memory declares `status:` in its frontmatter and says what is open in a `<!-- status -->`
// block; `recall.py --threads-compile` lists the open ones in ~/.claude/open-threads.generated.md,
// and this installs that file into each agent's instruction file as a managed block, the way
// src/agent-gates.js installs the compiled gates. The same file carries an INDEX line whenever
// MEMORY.md is past one of its budgets, so every new session is told to compact it, including
// on a box whose managed policy keeps user hooks from running.
//
// A SEPARATE module from agent-gates.js on purpose, sharing only agent-guidance.js's block and
// target plumbing. The gates code is heavily tested and has its own history of torn reads and
// per-agent sections; nothing here may change how it behaves, and an `off` on either block can
// never touch the other, because each closes over its own markers.
//
// The compiled file is read ONCE per call, and the bytes it checks are the bytes it installs
// (the gates' G2, for the same reason). recall.py always writes a header line carrying the first
// 16 hex digits of the SHA-256 of everything below it, then `## Open threads (N, managed)`. So:
//   * missing        nothing compiled yet: nothing to do, nothing written;
//   * unreadable     refused with the reason, nothing written;
//   * torn           no header, a header torn mid-line, an empty file, a sha that does not
//                    match, or no heading: refused, nothing written. recall.py never writes an
//                    empty file (zero threads is the header and the heading), so an empty read
//                    is a torn one;
//   * whole          installed for every agent when it lists a thread or an INDEX line, and
//                    REMOVED from every agent when it lists neither, so a closed thread leaves.

const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const { createManagedBlock, guidanceStatusAll, setGuidanceAll } = require('./agent-guidance');

const THREADS_BEGIN = '<!-- BEGIN permission-wildcarding: open threads (managed) -->';
const THREADS_END = '<!-- END permission-wildcarding: open threads -->';

// Beside gates.generated.md, and for the same reason: derived from a private memory store, so
// never in a checkout.
function compiledPath(home = os.homedir()) {
  return path.join(home, '.claude', 'open-threads.generated.md');
}

// recall.py _compile_threads_text's header and heading. Nothing older ever wrote this file, so
// unlike the gates there is no headerless form to accept: a text that does not open with the
// whole header line is refused, which also refuses a read torn inside it.
const HEADER = /^<!-- generated by recall\.py --threads-compile; sha ([0-9a-f]{16}) -->\n/;
const HEADING = /^## Open threads \((\d+), managed\)\n/;
const INDEX_PREFIX = '- **INDEX** ';

// The compiled file from ONE read, judged. See the header comment for the four states.
function readCompiled(home) {
  const file = compiledPath(home);
  let raw;
  try { raw = fs.readFileSync(file, 'utf8'); }
  catch (error) {
    if (error.code === 'ENOENT') return { state: 'missing' };
    return { state: 'refused', kind: 'unreadable', reason: `cannot read ${file} (${error.code || error.message})` };
  }
  const torn = (why) => ({ state: 'refused', kind: 'torn',
    reason: `${file} ${why} (read while it was being written, or edited by hand)` });
  const header = HEADER.exec(raw);
  if (!header) return torn('does not begin with the header recall.py writes');
  const below = raw.slice(header[0].length);
  const sha = crypto.createHash('sha256').update(below, 'utf8').digest('hex').slice(0, 16);
  if (sha !== header[1]) return torn('does not match the sha in its own header');
  const heading = HEADING.exec(below);
  if (!heading) return torn('has no `## Open threads (N, managed)` heading');
  const first = below.slice(heading[0].length).split('\n')[0];
  const index = first.startsWith(INDEX_PREFIX) ? first.slice(INDEX_PREFIX.length) : null;
  const count = Number(heading[1]);
  return { state: 'whole', count, index, wanted: count > 0 || index !== null, body: raw.trim() };
}

// The block, its body fixed to the text already read and checked, so two uses can never see two
// files. Built per call, never at require time, which would freeze whatever home was current.
function makeThreadsBlock(body) {
  return createManagedBlock({ begin: THREADS_BEGIN, end: THREADS_END, body });
}

// Why `on` cannot proceed, as a refusal row, or null. A missing compile is "nothing to do":
// the row carries no `error`, so an unattended caller logs nothing, and `refusal` lets a person's
// command say why nothing happened. `hint` is how this caller recompiles: the CLI's own command by
// default, and the extension passes its own, because a VSIX ships no `bin/` (2026-10-20).
const CLI_REFRESH_HINT = 'recompile with `wildcard-perms --open-threads refresh`';
function refusalRow(compiled, home, hint = CLI_REFRESH_HINT) {
  if (compiled.state === 'whole') return null;
  const file = compiledPath(home);
  if (compiled.state === 'missing') {
    return { agent: 'all', changed: false, path: file, on: false, refusal: 'missing',
      reason: `nothing compiled yet at ${file}`, error: null };
  }
  return { agent: 'all', changed: false, path: file, on: false, refusal: compiled.kind,
    reason: `${compiled.reason}: nothing was written`,
    error: `${compiled.reason}: nothing was written; ${hint}` };
}

// Every agent's file, from one read of the compiled file. Each row adds what that compile says:
// `compile` ('missing', 'refused' or 'whole'), `threads` (the heading's count), `index` (the
// INDEX line's text, or null), `wanted` (whether the compile asks for a block at all), and for a
// refused compile `refusal` and `reason`. A whole compile that wants no block is `current` once
// none is left in any of the agent's files, because the next install removes one.
function openThreadsStatusAll(homeOrOptions) {
  const options = typeof homeOrOptions === 'string' ? { home: homeOrOptions } : (homeOrOptions || {});
  const home = options.home ?? os.homedir();
  const compiled = readCompiled(home);
  const whole = compiled.state === 'whole';
  const block = makeThreadsBlock(whole && compiled.wanted ? compiled.body : '');
  return guidanceStatusAll(options, block).map((state) => {
    const row = {
      ...state, compile: compiled.state, threads: whole ? compiled.count : 0, index: whole ? compiled.index : null,
      wanted: whole && compiled.wanted, refusal: compiled.kind || null, reason: compiled.reason || null,
    };
    return whole && !compiled.wanted && state.readable
      ? { ...row, current: !state.on && !state.shadowedPaths?.length } : row;
  });
}

// Install or remove the block in every installed agent's instruction file: Claude's CLAUDE.md
// and Codex's AGENTS.md, or its nonempty AGENTS.override.md, which setGuidanceAll selects and
// re-checks under the lock. `off` needs no compile and goes ahead whatever the file holds. `on`
// installs the compile it read, removes the block when that compile lists nothing, and refuses
// a missing, unreadable or torn compile with every instruction file left as it was.
// `options.inPlaceFallback: false` is for the unattended callers (the extension's ensure and
// `--open-threads refresh`), as it is for the gates. `options.refreshHint` replaces the CLI wording
// in a refused compile's error (refusalRow).
function setOpenThreadsAll(on, options = {}) {
  const home = options.home ?? os.homedir();
  const { refreshHint, ...rest } = options;
  const shared = { ...rest, backupSuffix: 'pre-open-threads' };
  if (!on) {
    return setGuidanceAll(false, { ...shared, block: makeThreadsBlock('') })
      .map((row) => ({ ...row, threads: 0, index: null, wanted: false }));
  }
  const compiled = readCompiled(home);
  const refused = refusalRow(compiled, home, refreshHint);
  if (refused) return [refused];
  return setGuidanceAll(compiled.wanted, { ...shared, block: makeThreadsBlock(compiled.body) })
    .map((row) => ({ ...row, threads: compiled.count, index: compiled.index, wanted: compiled.wanted }));
}

module.exports = {
  THREADS_BEGIN, THREADS_END, compiledPath, openThreadsStatusAll, setOpenThreadsAll,
};
