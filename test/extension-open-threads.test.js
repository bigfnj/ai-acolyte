'use strict';

// The extension's half of the open threads (2026-10-19): the machine-scoped switch and what
// "switched off stays off" means, activation's install and its deferred compile, the corpus
// watcher's dispatch to the gates and the threads, the compiled-file watcher, the toggle command,
// and deactivate clearing the recompile's timer.
//
// A window over a temp home with the REAL memoryLint over a real store, so the activation
// decision and the watcher's store check read what recall.py would read. The toolbox Python is
// recorded, never run: a `--threads-compile` call writes the compile the test hands it, the way
// recall.py would, and answers success. The threads' two timers (2.5 s after an edit, 4 s after
// activation) are held for the test to fire; every other timer runs, unref'd.
//
// Harness copied, not shared, per the suite's standing decision
// (test/extension-activation.test.js:505#sharing).

const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Module = require('node:module');
const { EventEmitter } = require('node:events');

const BEGIN = '<!-- BEGIN permission-wildcarding: open threads (managed) -->';
const THREAD_TIMERS = new Set([2500, 4000]);

function compiled({ threads = [], index = null } = {}) {
  const lines = [...(index ? [`- **INDEX** ${index}`] : []), ...threads];
  const body = `## Open threads (${threads.length}, managed)\n${lines.map((line) => `${line}\n`).join('')}`;
  const sha = crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16);
  return `<!-- generated by recall.py --threads-compile; sha ${sha} -->\n${body}`;
}
const ONE = compiled({ threads: ['- **AWAITING** The owner decides. (a)'] });
const TWO = compiled({ threads: ['- **OPEN** First. (a)', '- **BLOCKED** Second. (b)'] });
const NONE = compiled();

const memory = (status, text = 'Synthetic.') => `---\nname: m\ndescription: synthetic\n${status ? `status: ${status}\n` : ''}---\n\n`
  + `The body.\n${status ? `\n<!-- status -->\n${text}\n<!-- /status -->\n` : ''}`;

// `tiers` maps a setting key to VS Code's per-tier inspect() object; `prepare(box)` seeds the home
// before activation; `compileWrites` is what a `--threads-compile` writes (a string, or null to
// write nothing and fail).
async function threadsWindow(t, { tiers = {}, prepare = () => {}, compileWrites = ONE } = {}) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'acolyte-threads-window-'));
  t.after(() => { try { fs.rmSync(home, { recursive: true, force: true, maxRetries: 3, retryDelay: 50 }); } catch {} });
  const claude = path.join(home, '.claude');
  const store = path.join(claude, 'projects', 'p', 'memory');
  const other = path.join(claude, 'projects', 'q', 'memory');
  for (const dir of [store, other]) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(store, 'MEMORY.md'), '# Memory Index\n- [a](a.md) - hook\n');
  // Four memories against the other store's one, so the store that compiles (the one with the
  // most memory files, memoryLint.js pickPrimary) stays this one whatever a test deletes.
  for (const name of ['a.md', 'extra.md', 'b.md', 'c.md']) fs.writeFileSync(path.join(store, name), memory(null));
  fs.writeFileSync(path.join(other, 'MEMORY.md'), '# Other\n');
  fs.writeFileSync(path.join(claude, 'settings.json'), JSON.stringify({ permissions: { allow: [] } }));
  fs.writeFileSync(path.join(claude, 'CLAUDE.md'), '# Mine\n');
  fs.mkdirSync(path.join(home, '.codex'));
  fs.writeFileSync(path.join(home, '.codex', 'AGENTS.md'), '# Codex mine\n');
  const python = path.join(home, 'toolbox', 'python', '.venv', 'Scripts', 'python.exe');
  fs.mkdirSync(path.dirname(python), { recursive: true });
  fs.writeFileSync(python, '');
  const threadsFile = path.join(claude, 'open-threads.generated.md');
  const box = { home, store, other, threadsFile, claudeMd: path.join(claude, 'CLAUDE.md'), agentsMd: path.join(home, '.codex', 'AGENTS.md') };
  prepare(box);

  const watchers = [];
  const spawns = [];
  const held = [];       // the threads' timers: { ms, fn, cleared }
  const commands = new Map();
  const warnings = [];
  const modals = [];     // each warning with the buttons it offered
  const infos = [];
  const channel = [];
  const configListeners = [];
  const state = { compileWrites, warningAnswer: undefined, hold: false, holding: [] };
  const counters = { memoryReport: 0 };
  const disposable = () => ({ dispose() {} });
  const vscode = {
    StatusBarAlignment: { Left: 1, Right: 2 }, ConfigurationTarget: { Global: 1, Workspace: 2, WorkspaceFolder: 3 },
    ProgressLocation: { Notification: 15 }, DiagnosticSeverity: { Error: 0, Warning: 1, Information: 2, Hint: 3 },
    RelativePattern: class RelativePattern { constructor(base, pattern) { this.base = base; this.pattern = pattern; } },
    ThemeColor: class ThemeColor {}, Uri: { file: (p) => ({ fsPath: p }) },
    Range: class Range {}, Diagnostic: class Diagnostic {},
    languages: { createDiagnosticCollection() { return { set() {}, delete() {}, clear() {}, dispose() {} }; } },
    commands: { registerCommand(id, fn) { commands.set(id, fn); return disposable(); }, executeCommand() {} },
    window: {
      createOutputChannel() { return { appendLine: (line) => channel.push(String(line)), append() {}, show() {}, clear() {}, dispose() {} }; },
      createStatusBarItem() { return { show() {}, hide() {}, dispose() {} }; },
      registerWebviewViewProvider() { return disposable(); }, onDidChangeActiveTextEditor() { return disposable(); },
      withProgress(options, task) { return task({ report() {} }); },
      setStatusBarMessage() { return disposable(); }, showErrorMessage(message) { warnings.push(String(message)); },
      showWarningMessage(message, ...rest) {
        warnings.push(String(message));
        modals.push({ message: String(message), items: rest.filter((item) => typeof item === 'string') });
        return Promise.resolve(state.warningAnswer);
      },
      showInformationMessage(message) { infos.push(String(message)); return Promise.resolve(undefined); },
    },
    workspace: {
      isTrusted: true, workspaceFolders: [{ uri: { fsPath: path.join(home, 'repo') } }],
      createFileSystemWatcher(pattern) {
        const watcher = { pattern, handlers: { change: [], create: [], delete: [] }, disposed: false, dispose() { watcher.disposed = true; },
          onDidChange(h) { watcher.handlers.change.push(h); return disposable(); },
          onDidCreate(h) { watcher.handlers.create.push(h); return disposable(); },
          onDidDelete(h) { watcher.handlers.delete.push(h); return disposable(); } };
        watchers.push(watcher);
        return watcher;
      },
      getConfiguration() {
        return {
          get: (key, fallback) => {
            const value = tiers[key];
            if (value) return value.workspaceFolderValue ?? value.workspaceValue ?? value.globalValue ?? fallback;
            return key === 'autoLearn.enabled' || key === 'guidance.enabled' ? false : fallback;
          },
          inspect: (key) => tiers[key] || (key === 'guidance.enabled' ? { globalValue: false } : {}),
          update: async (key, value, target) => {
            tiers[key] = { ...(tiers[key] || {}), globalValue: value, updatedAt: target };
            for (const listener of configListeners) listener({ affectsConfiguration: (section) => `permissionWildcarding.${key}`.startsWith(section) });
          },
        };
      },
      onDidChangeConfiguration(listener) { configListeners.push(listener); return disposable(); },
      onDidChangeWorkspaceFolders() { return disposable(); },
      onDidSaveTextDocument() { return disposable(); }, onDidOpenTextDocument() { return disposable(); },
    },
  };
  const realChildProcess = require('node:child_process');
  const recorded = {
    ...realChildProcess,
    execFile(file, args, options, callback) {
      if (file !== python) return realChildProcess.execFile.apply(this, arguments);
      const done = typeof options === 'function' ? options : callback;
      spawns.push({ args, env: (typeof options === 'object' && options?.env) || {} });
      const child = new EventEmitter();
      // What this compile writes is what the corpus was when it was spawned, as recall.py reads it.
      const writes = state.compileWrites;
      const finish = () => {
        let err = null;
        if (args.includes('--threads-compile')) {
          if (writes === null) err = Object.assign(new Error('exit 1'), { code: 1 });
          else fs.writeFileSync(threadsFile, writes);
        }
        done(err, '', err ? '[recall] refusing to compile open threads: the test said so' : '');
        child.emit('exit', err ? 1 : 0, null);
        child.emit('close', err ? 1 : 0, null);
      };
      // `state.hold`: the compile runs until the test calls its finish (state.holding).
      if (state.hold && args.includes('--threads-compile')) state.holding.push(finish);
      else setImmediate(finish);
      return child;
    },
  };
  const extensionPath = require.resolve('../vscode-extension/extension');
  const rootSrc = path.resolve(__dirname, '..', 'src');
  const originalLoad = Module._load;
  const saved = Object.fromEntries(['HOME', 'USERPROFILE', 'CODEX_HOME', 'CODEX_TOOLBOX'].map((key) => [key, process.env[key]]));
  Object.assign(process.env, { HOME: home, USERPROFILE: home, CODEX_HOME: path.join(home, '.codex'), CODEX_TOOLBOX: path.join(home, 'toolbox') });
  const realSetTimeout = global.setTimeout;
  const realClearTimeout = global.clearTimeout;
  global.setTimeout = (fn, ms, ...rest) => {
    if (THREAD_TIMERS.has(ms)) { const entry = { ms, fn, cleared: false }; held.push(entry); return entry; }
    const handle = realSetTimeout(fn, ms, ...rest);
    if (typeof handle?.unref === 'function') handle.unref();
    return handle;
  };
  global.clearTimeout = (handle) => {
    if (held.includes(handle)) { handle.cleared = true; return undefined; }
    return realClearTimeout(handle);
  };
  Module._load = function load(request, parent, isMain) {
    if (request === 'vscode') return vscode;
    if (request === 'os') return { ...os, homedir: () => home };
    if ((request === 'child_process' || request === 'node:child_process') && parent?.filename === extensionPath) return recorded;
    // The REAL memoryLint, with the extension's memoryReport() calls counted: it reads every file
    // in the store, and the unattended paths must not.
    if (request === './memoryLint' && parent?.filename === extensionPath) {
      const real = originalLoad.call(this, request, parent, isMain);
      return { ...real, memoryReport: (...args) => { counters.memoryReport += 1; return real.memoryReport(...args); } };
    }
    if (parent?.filename === extensionPath && request.startsWith('./src/')) {
      return originalLoad.call(this, path.join(rootSrc, request.slice('./src/'.length)), parent, isMain);
    }
    return originalLoad.call(this, request, parent, isMain);
  };
  const purge = () => {
    for (const key of Object.keys(require.cache)) {
      if (key.startsWith(rootSrc + path.sep) || key.startsWith(path.dirname(extensionPath) + path.sep)) delete require.cache[key];
    }
  };
  purge();
  const extension = require(extensionPath);
  let closed = false;
  const close = async () => {
    if (closed) return;
    closed = true;
    try { await extension.deactivate(); } finally {
      global.setTimeout = realSetTimeout;
      global.clearTimeout = realClearTimeout;
      Module._load = originalLoad;
      for (const [key, value] of Object.entries(saved)) {
        if (value === undefined) delete process.env[key];
        else process.env[key] = value;
      }
      purge();
    }
  };
  t.after(close);
  try { extension.activate({ subscriptions: [] }); } catch (error) { await close(); throw error; }
  const settle = () => new Promise((resolve) => setImmediate(() => setImmediate(resolve)));
  const live = () => held.filter((entry) => !entry.cleared && !entry.fired);
  return {
    ...box, extension, watchers, spawns, held, commands, warnings, modals, infos, channel, state, counters, tiers, close, settle, live,
    claude: () => fs.readFileSync(box.claudeMd, 'utf8'),
    codex: () => fs.readFileSync(box.agentsMd, 'utf8'),
    compiles: () => spawns.filter((spawn) => spawn.args.includes('--threads-compile')),
    // A settings edit the way VS Code reports it, after the tiers were changed by hand.
    fireConfig(section) {
      for (const listener of configListeners) listener({ affectsConfiguration: (prefix) => section.startsWith(prefix) });
    },
    // The *.md watcher of a store, fired for `file` as VS Code fires it.
    fireCorpus(dir, file, kind = 'change') {
      const watcher = watchers.find((w) => w.pattern?.pattern === '*.md' && w.pattern.base?.fsPath === dir && !w.disposed);
      assert.ok(watcher, `precondition: ${dir} has a corpus watcher`);
      for (const fn of watcher.handlers[kind]) fn({ fsPath: path.join(dir, file) });
    },
    fireCompiled(kind = 'change') {
      const watcher = watchers.find((w) => w.pattern?.pattern === 'open-threads.generated.md');
      assert.ok(watcher, 'precondition: the compiled file is watched');
      for (const fn of watcher.handlers[kind]) fn({ fsPath: threadsFile });
    },
    // Run every live threads timer, then let the recorded compile answer and the install run.
    async fireTimers() {
      for (const entry of live()) { entry.fired = true; entry.fn(); }
      await settle();
      await settle();
    },
  };
}

const installedIn = (text) => text.includes(BEGIN);

test('activation installs the last compile into every agent, and is write-free once it is settled', async (t) => {
  const app = await threadsWindow(t, { prepare: (box) => fs.writeFileSync(box.threadsFile, ONE) });
  assert.ok(installedIn(app.claude()) && installedIn(app.codex()), 'activation installed the compiled block');
  assert.ok(app.claude().includes('- **AWAITING** The owner decides. (a)'));
  const before = { claude: app.claude(), codex: app.codex(), claudeStat: fs.statSync(app.claudeMd).mtimeMs };
  app.fireCompiled('change');
  assert.deepEqual({ claude: app.claude(), codex: app.codex(), claudeStat: fs.statSync(app.claudeMd).mtimeMs }, before,
    'a settled install is not rewritten');
  // MUTATION: drop ensureOpenThreads() from activate() and the first assertion fails.
});

