test('the corpus watcher hands every change to both the gates and the threads, and each decides', async (t) => {
  const app = await threadsWindow(t, { tiers: { 'gates.enabled': { globalValue: false } } });
  await app.fireTimers();
  assert.deepEqual(app.compiles(), [], 'precondition: activation\'s check compiled nothing on this store');
  // A memory with no status, while nothing is compiled: no recompile.
  app.fireCorpus(app.store, 'extra.md');
  assert.deepEqual(app.live(), [], 'an edit that cannot move the threads arms nothing');
  // MEMORY.md: the gates skip it, the threads compile for its health, with gates switched off.
  // That compile lists nothing, so the status edit below arms on its own words alone.
  app.state.compileWrites = NONE;
  app.fireCorpus(app.store, 'MEMORY.md');
  assert.deepEqual(app.live().map((entry) => entry.ms), [2500], 'an index edit arms the threads recompile, gates off or not');
  await app.fireTimers();
  assert.equal(app.compiles().length, 1, 'and it compiles');
  // A memory that now declares a status, while the compile lists none.
  app.state.compileWrites = ONE;
  fs.writeFileSync(path.join(app.store, 'extra.md'), memory('blocked'));
  app.fireCorpus(app.store, 'extra.md');
  assert.deepEqual(app.live().map((entry) => entry.ms), [2500], 'a status edit arms it, on what the file says');
  // Two events in a burst are one compile.
  app.fireCorpus(app.store, 'extra.md');
  assert.equal(app.live().length, 1, 'debounced');
  await app.fireTimers();
  assert.equal(app.compiles().length, 2);
  // The compile now lists a thread, so an edit that drops `status:` entirely, or a deletion,
  // still recompiles: either may be the closure.
  assert.ok(installedIn(app.claude()), 'precondition: the thread is installed');
  fs.writeFileSync(path.join(app.store, 'extra.md'), memory(null));
  app.state.compileWrites = NONE;
  app.fireCorpus(app.store, 'extra.md');
  assert.deepEqual(app.live().map((entry) => entry.ms), [2500], 'a closure is recompiled');
  await app.fireTimers();
  assert.equal(installedIn(app.claude()), false, 'and the closed thread leaves the block');
  fs.writeFileSync(app.threadsFile, ONE);
  fs.rmSync(path.join(app.store, 'extra.md'));
  app.fireCorpus(app.store, 'extra.md', 'delete');
  assert.deepEqual(app.live().map((entry) => entry.ms), [2500], 'a deletion is recompiled while a thread is listed');
  await app.fireTimers();
  // A store that does not compile: no recompile, whatever changed in it. Which store compiles is
  // asked once per burst, when the timer fires, so the burst arms and then compiles nothing.
  const compiledBefore = app.compiles().length;
  fs.writeFileSync(path.join(app.other, 'x.md'), memory('open'));
  app.fireCorpus(app.other, 'x.md');
  app.fireCorpus(app.other, 'MEMORY.md');
  await app.fireTimers();
  assert.equal(app.compiles().length, compiledBefore, 'another store\'s change is skipped: the compile reads one store');
  // MUTATION: in memoryCorpusChanged, call only gatesCorpusBump and nothing here arms; route the
  // threads through gatesCorpusBump's early returns (MEMORY.md, gatesEnabled) and the index edit
  // arms nothing; drop compiledListsThreads from threadsMayChange and the closure and deletion
  // arm nothing; drop the store check and the other store arms one.
});

