'use strict';

// The --gates argv wiring, exercised through the real CLI against a throwaway home so
// nothing lands in the developer's ~/.claude. The block logic is covered in
// agent-gates.test.js; what is tested here is the part only argv can get wrong: that
// `refresh` behaves as a SessionStart hook must (quiet, non-zero-exit-free, idempotent),
// that a bad verb is rejected, and that `off` leaves a coexisting guidance block alone.

const test = require('node:test');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const CLI = path.resolve(__dirname, '..', 'bin', 'wildcard-perms');
const COMPILED = '## Standing gates (1 memories, managed)\n\n- **Test gate.** Pass: nothing.';

function runCli(home, args) {
  const root = path.parse(home).root;
  return spawnSync(process.execPath, [CLI, ...args], {
    cwd: home, encoding: 'utf8', windowsHide: true,
    env: {
      ...process.env, HOME: home, USERPROFILE: home, CODEX_HOME: path.join(home, '.codex'),
      HOMEDRIVE: root.replace(/[\\/]$/, ''), HOMEPATH: home.slice(root.length - 1),
    },
  });
}

// A home with an instruction file and a pre-compiled gates file, so `--gates on` has
// something real to install without this test needing python.
function tempHome(t, { compiled = COMPILED } = {}) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'permission-wildcarding-gates-'));
  fs.mkdirSync(path.join(home, '.claude'), { recursive: true });
  fs.writeFileSync(path.join(home, '.claude', 'settings.json'), '{}\n');
  fs.writeFileSync(path.join(home, '.claude', 'CLAUDE.md'), '# Mine\n');
  if (compiled !== null) {
    fs.writeFileSync(path.join(home, '.claude', 'gates.generated.md'), compiled + '\n');
  }
  t.after(() => fs.rmSync(home, { recursive: true, force: true }));
  return home;
}

const claudeMd = (home) => fs.readFileSync(path.join(home, '.claude', 'CLAUDE.md'), 'utf8');

test('CLI --gates on installs, and status reports it', (t) => {
  const home = tempHome(t);

  const status = runCli(home, ['--gates', 'status']);
  assert.equal(status.status, 0, status.stderr);
  assert.match(status.stdout, /OFF/);

  const on = runCli(home, ['--gates', 'on']);
  assert.equal(on.status, 0, on.stderr);
  assert.match(on.stdout, /ON/);
  assert.match(claudeMd(home), /BEGIN permission-wildcarding: memory gates/);
  assert.ok(claudeMd(home).startsWith('# Mine\n'), 'user text keeps its place');
  assert.match(runCli(home, ['--gates', 'status']).stdout, /ON/);
});

// Per agent (`agents:`, 2026-10-14). recall.py writes one section per agent once a gate names
// the agents it is for (_compile_gates_text); built here the way it writes them. Status names
// each agent's own count, and an `on` that turns an agent off, because the compile gives it no
// gates, says so instead of ON.
test('CLI --gates status counts each agent, and on names an agent the compile gives none', (t) => {
  const crypto = require('node:crypto');
  const render = (bodies) => {
    if (!bodies.length) return '';
    const body = bodies.join('\n');
    const sha = crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16);
    return `<!-- generated by recall.py --gates-compile; sha ${sha} -->\n## Standing gates (${bodies.length} memories, managed)\n\n${body}\n`;
  };
  const perAgent = (claude, codex) => {
    const sections = [render(claude), render(codex)];
    return `<!-- generated by recall.py --gates-compile; per agent: claude ${Buffer.byteLength(sections[0])}, `
      + `codex ${Buffer.byteLength(sections[1])} -->\n${sections.join('')}`;
  };
  const home = tempHome(t, { compiled: null });
  fs.mkdirSync(path.join(home, '.codex'));
  fs.writeFileSync(path.join(home, '.codex', 'AGENTS.md'), '# Mine\n');
  const compiled = path.join(home, '.claude', 'gates.generated.md');
  fs.writeFileSync(compiled, perAgent(['- Shared.'], ['- Shared.', '- Codex only.']));

  assert.equal(runCli(home, ['--gates', 'on']).status, 0);
  const status = runCli(home, ['--gates', 'status']).stdout;
  assert.match(status, /\[claude\]: ON, 1 gate \(/);
  assert.match(status, /\[codex\]: ON, 2 gates \(/);

  fs.writeFileSync(compiled, perAgent([], ['- Shared.', '- Codex only.']));
  const on = runCli(home, ['--gates', 'on']);
  assert.equal(on.status, 0, on.stderr);
  assert.match(on.stdout, /\[claude\]: OFF, none compiled for claude — /);
  assert.equal(claudeMd(home), '# Mine\n', 'Claude, with no gates left, has its block removed');
  assert.match(runCli(home, ['--gates', 'status']).stdout, /\[claude\]: OFF, 0 gates \(none compiled for claude\)/);

  // MUTATION: drop `${count}` from the status line in gates() in bin/wildcard-perms and the
  // counts are gone; print `cmd.toUpperCase()` for every row and the removal reads "ON".
});

test('CLI --gates off is a byte-for-byte round trip', (t) => {
  const home = tempHome(t);
  const before = claudeMd(home);
  runCli(home, ['--gates', 'on']);
  const off = runCli(home, ['--gates', 'off']);
  assert.equal(off.status, 0, off.stderr);
  assert.equal(claudeMd(home), before);
});

// The SessionStart contract. A hook's stdout can be folded into session context, so an
// unchanged refresh has to say nothing at all, and it must never exit non-zero just
// because there was no work to do.
test('CLI --gates refresh is quiet and exit-0 when nothing changed', (t) => {
  const home = tempHome(t);
  runCli(home, ['--gates', 'on']);

  const first = runCli(home, ['--gates', 'refresh']);
  assert.equal(first.status, 0, first.stderr);
  assert.equal(first.stdout.trim(), '', 'an unchanged refresh must print nothing');
  // This home has no memory dir, which is a normal state and must not surface a Python
  // traceback: a hook that vomits a stack trace on every session start is worse than useless.
  assert.doesNotMatch(first.stderr, /Traceback|FileNotFoundError/,
    'a missing memory dir must be handled, not thrown');

  const second = runCli(home, ['--gates', 'refresh']);
  assert.equal(second.status, 0);
  assert.equal(second.stdout.trim(), '', 'still quiet on a repeat');
  assert.match(claudeMd(home), /BEGIN permission-wildcarding: memory gates/);
});

// `refresh` is the unattended verb (a SessionStart hook), so it writes with no in-place
// fallback: a CLAUDE.md held through every rename attempt is left whole and the next session
// retries. `on`, run by a person who sees the result, keeps the fallback. The hold is a
// preload that fails every rename onto CLAUDE.md, as Windows does while another process has
// it open; TOOLBOX_PYTHON names a file that does not exist, so no Python runs.
test('CLI --gates refresh never writes a held CLAUDE.md in place; --gates on still does', (t) => {
  const home = tempHome(t);
  const file = path.join(home, '.claude', 'CLAUDE.md');
  const preload = path.join(home, 'hold-claude-md.js');
  fs.writeFileSync(preload, `const fs = require('fs'), path = require('path');
const real = fs.renameSync;
fs.renameSync = (from, to) => {
  if (path.resolve(String(to)) === ${JSON.stringify(path.resolve(file))}) {
    throw Object.assign(new Error('EPERM: operation not permitted, rename'), { code: 'EPERM' });
  }
  return real(from, to);
};
`);
  const held = (args) => {
    const root = path.parse(home).root;
    return spawnSync(process.execPath, ['--require', preload, CLI, ...args], {
      cwd: home, encoding: 'utf8', windowsHide: true,
      env: {
        ...process.env, HOME: home, USERPROFILE: home, CODEX_HOME: path.join(home, '.codex'),
        HOMEDRIVE: root.replace(/[\\/]$/, ''), HOMEPATH: home.slice(root.length - 1),
        TOOLBOX_PYTHON: path.join(home, 'no-such-python.exe'),
      },
    });
  };
  const refresh = held(['--gates', 'refresh']);
  assert.equal(claudeMd(home), '# Mine\n', `the held file was written in place: ${refresh.stderr}`);
  assert.equal(refresh.status, 1);
  assert.match(refresh.stderr, /stayed held through \d+ rename attempts/);
  assert.deepEqual(fs.readdirSync(path.join(home, '.claude')).filter((name) => name.endsWith('.tmp')), []);

  const on = held(['--gates', 'on']);
  assert.equal(on.status, 0, on.stderr);
  assert.match(claudeMd(home), /BEGIN permission-wildcarding: memory gates/,
    'a person running --gates on still gets the in-place fallback');

  // MUTATION: pass `{ inPlaceFallback: true }` (or nothing) to setGatesAll in gates() in
  // bin/wildcard-perms and the refresh rewrites CLAUDE.md in place: the first assertion fails.
});

// Ported from rampage 7139659. `refresh` is the command the install refusals advise, so
// printing them from refresh itself told a SessionStart hook to run itself, every session.
// Two cases, both with nothing compiled: a compile that could not run at all, and a stand-in
// compile that ran, compiled nothing and warned on stderr, which refresh used to swallow.
test('CLI --gates refresh says what happened, never advises refresh, and passes compile warnings through', (t) => {
  const home = tempHome(t, { compiled: null });
  const root = path.parse(home).root;
  const env = {
    ...process.env, HOME: home, USERPROFILE: home, CODEX_HOME: path.join(home, '.codex'),
    HOMEDRIVE: root.replace(/[\\/]$/, ''), HOMEPATH: home.slice(root.length - 1),
  };
  delete env.TOOLBOX_PYTHON;
  const run = (extra) => spawnSync(process.execPath, [CLI, '--gates', 'refresh'],
    { cwd: home, encoding: 'utf8', windowsHide: true, env: { ...env, ...extra } });

  // The compile cannot run: the interpreter named does not exist.
  const failed = run({ TOOLBOX_PYTHON: path.join(home, 'no-such-python.exe') });
  assert.equal(failed.status, 1);
  assert.match(failed.stderr, /refresh: compile failed, and nothing was installed \(.*ENOENT/);
  assert.doesNotMatch(failed.stderr, /--gates refresh`|--gates-compile/, 'no advice to run what just ran');
  assert.doesNotMatch(failed.stderr, /installing whatever was last compiled/, 'nothing was installed, so it must not say so');
  assert.equal(claudeMd(home), '# Mine\n');

  // The compile runs, prints a warning, exits 0 and compiles nothing. A stand-in python on
  // PATH, so this needs no interpreter and no model.
  const bin = path.join(home, 'bin');
  fs.mkdirSync(bin);
  const WARNING = '[recall] stand-in warning: a store could not be listed';
  if (process.platform === 'win32') {
    fs.writeFileSync(path.join(bin, 'python.cmd'), `@echo off\r\necho ${WARNING} 1>&2\r\nexit /b 0\r\n`);
  } else {
    fs.writeFileSync(path.join(bin, 'python'), `#!/bin/sh\necho '${WARNING}' >&2\nexit 0\n`, { mode: 0o755 });
  }
  const system = process.platform === 'win32' ? path.join(process.env.SystemRoot, 'System32') : '/usr/bin:/bin';
  const empty = run({ PATH: [bin, system].join(path.delimiter) });
  assert.equal(empty.status, 1);
  assert.ok(empty.stderr.includes(WARNING), `the compile's own warning reaches stderr: ${empty.stderr}`);
  assert.match(empty.stderr, /refresh: the compile found no scope:global gate blocks, so there is nothing to install/);
  assert.doesNotMatch(empty.stderr, /--gates refresh`|--gates-compile/, 'no advice to run what just ran');
  assert.equal(empty.stdout, '', 'and stdout, which a SessionStart hook can fold into context, stays empty');
  assert.equal(claudeMd(home), '# Mine\n');

  // MUTATION: delete the `if (cmd === 'refresh' && refused)` block in gates() in
  // bin/wildcard-perms and both cases print the refusal's "run `recall.py --gates-compile`
  // first (`wildcard-perms --gates refresh` ...)" advice. Delete the `else if
  // (compile.stderr)` pass-through and the WARNING assertion fails.
});

