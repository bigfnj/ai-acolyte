'use strict';

// `wildcard-perms --open-threads on|off|status|refresh` (2026-10-19), through the real CLI against
// a throwaway home. The block logic is covered in test/agent-open-threads.test.js and the compile
// in test/threads-compile.sh; what is tested here is what only argv and the process can get
// wrong: that the verb dispatches at all (a verb in VERBS with no branch falls into hook mode,
// which rewrites settings.json), that `refresh` compiles with `--threads-compile` and then
// installs, quietly and with no in-place fallback, and that every refusal says what happened.
//
// No real Python: "Python" is this node binary (TOOLBOX_PYTHON) with a preload that stands in for
// recall.py whenever the script it was asked to run is named recall.py. The stand-in logs its
// arguments and, for `--threads-compile`, copies ACOLYTE_STUB_THREADS over the compiled file the
// way recall.py writes it, or fails, or warns, as the test asks.

const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const CLI = path.resolve(__dirname, '..', 'bin', 'wildcard-perms');
const BEGIN = '<!-- BEGIN permission-wildcarding: open threads (managed) -->';

function compiled({ threads = [], index = null } = {}) {
  const lines = [...(index ? [`- **INDEX** ${index}`] : []), ...threads];
  const body = `## Open threads (${threads.length}, managed)\n${lines.map((line) => `${line}\n`).join('')}`;
  const sha = crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16);
  return `<!-- generated by recall.py --threads-compile; sha ${sha} -->\n${body}`;
}
const TWO = compiled({ threads: ['- **OPEN** First. (a)', '- **AWAITING** Second. (b)'] });
const NONE = compiled();
const INDEXED = compiled({ threads: ['- **OPEN** First. (a)'], index: 'MEMORY.md is 141 lines (budget 140): compact it.' });

const STUB_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'acolyte-cli-threads-stub-'));
test.after(() => fs.rmSync(STUB_DIR, { recursive: true, force: true }));
const STUB = path.join(STUB_DIR, 'recall-preload.js');
fs.writeFileSync(STUB, `'use strict';
const fs = require('fs');
const path = require('path');
if (path.basename(process.argv[1] || '') === 'recall.py') {
  const args = process.argv.slice(2);
  if (process.env.ACOLYTE_STUB_LOG) fs.appendFileSync(process.env.ACOLYTE_STUB_LOG, JSON.stringify(args) + '\\n');
  if (args[0] !== '--threads-compile') { process.stderr.write('[recall] the stub has no answer\\n'); process.exit(1); }
  if (process.env.ACOLYTE_STUB_MODE === 'fail') { process.stderr.write('[recall] refusing to compile open threads: the stub was told to\\n'); process.exit(1); }
  if (process.env.ACOLYTE_STUB_MODE === 'warn') process.stderr.write('[recall] open thread left out: c.md: unknown status \\'wip\\'\\n');
  const home = process.env.USERPROFILE || process.env.HOME;
  fs.copyFileSync(process.env.ACOLYTE_STUB_THREADS, path.join(home, '.claude', 'open-threads.generated.md'));
  process.stdout.write('compiled\\n');
  process.exit(0);
}
`);

const AMBIENT = ['TOOLBOX_PYTHON', 'CODEX_TOOLBOX', 'RECALL_MEMORY_DIR', 'RECALL_MEMORY_DIRS', 'RECALL_REEXEC',
  'NODE_OPTIONS', 'ACOLYTE_STUB_MODE', 'ACOLYTE_STUB_THREADS', 'ACOLYTE_STUB_LOG'];

function setup(t, { codex = true, compiledText = null } = {}) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'acolyte-cli-threads-'));
  t.after(() => fs.rmSync(home, { recursive: true, force: true, maxRetries: 3, retryDelay: 50 }));
  fs.mkdirSync(path.join(home, '.claude'), { recursive: true });
  // An allow list the hook's wildcarding pass would rewrite, so a fall-through to hook mode
  // shows up as a changed settings.json.
  fs.writeFileSync(path.join(home, '.claude', 'settings.json'),
    `${JSON.stringify({ permissions: { allow: ['Bash(git status)', 'Bash(git status --short)', 'Bash(git status -s)'] } }, null, 2)}\n`);
  fs.writeFileSync(path.join(home, '.claude', 'CLAUDE.md'), '# Mine\n');
  if (codex) {
    fs.mkdirSync(path.join(home, '.codex'));
    fs.writeFileSync(path.join(home, '.codex', 'AGENTS.md'), '# Codex mine\n');
  }
  const compiledFile = path.join(home, '.claude', 'open-threads.generated.md');
  if (compiledText !== null) fs.writeFileSync(compiledFile, compiledText);
  const fixture = path.join(home, 'fixture.md');
  fs.writeFileSync(fixture, TWO);
  const log = path.join(home, 'recall-calls.jsonl');
  const root = path.parse(home).root;
  const run = (args, extra = {}, preload = STUB) => {
    const base = { ...process.env };
    for (const name of AMBIENT) delete base[name];
    return spawnSync(process.execPath, [CLI, ...args], {
      cwd: home, encoding: 'utf8', windowsHide: true, timeout: 60000, input: '',
      env: {
        ...base, HOME: home, USERPROFILE: home, CODEX_HOME: path.join(home, '.codex'),
        HOMEDRIVE: root.replace(/[\\/]$/, ''), HOMEPATH: home.slice(root.length - 1),
        TOOLBOX_PYTHON: process.execPath, ACOLYTE_STUB_THREADS: fixture, ACOLYTE_STUB_LOG: log,
        // Forward slashes: NODE_OPTIONS reads a backslash inside quotes as an escape.
        NODE_OPTIONS: `--require "${preload.split(path.sep).join('/')}"`,
        ...extra,
      },
    });
  };
  return {
    home, run, fixture, compiledFile,
    claude: () => fs.readFileSync(path.join(home, '.claude', 'CLAUDE.md'), 'utf8'),
    codex: () => fs.readFileSync(path.join(home, '.codex', 'AGENTS.md'), 'utf8'),
    settings: () => fs.readFileSync(path.join(home, '.claude', 'settings.json'), 'utf8'),
    calls: () => (fs.existsSync(log) ? fs.readFileSync(log, 'utf8').split('\n').filter(Boolean).map((line) => JSON.parse(line)) : []),
  };
}

test('--help documents --open-threads', (t) => {
  const s = setup(t);
  const help = s.run(['--help']);
  assert.equal(help.status, 0, help.stderr);
  assert.ok(help.stdout.includes('usage: wildcard-perms --open-threads on|off|status|refresh\n'),
    '--open-threads is dispatched but undocumented');
});

test('every --open-threads verb dispatches, and none falls through to hook mode', (t) => {
  const s = setup(t, { compiledText: TWO });
  const before = s.settings();
  for (const verb of ['status', 'on', 'off', 'refresh', 'bogus', '']) {
    const run = s.run(['--open-threads', ...(verb ? [verb] : [])]);
    assert.match(`${run.stdout}${run.stderr}`, /open threads|--open-threads/, `${verb || '(no verb)'} reached the verb`);
    assert.equal(s.settings(), before, `${verb || '(no verb)'}: settings.json is untouched, so hook mode never ran`);
  }
  // MUTATION: delete the `--open-threads` dispatch branch in bin/wildcard-perms. Every verb then
  // falls into hook mode, prints nothing about open threads, and rewrites settings.json.
});

test('status names each agent, its thread count and the INDEX line; on installs and off removes', (t) => {
  const s = setup(t, { compiledText: INDEXED });
  const status = s.run(['--open-threads', 'status']);
  assert.equal(status.status, 0, status.stderr);
  assert.match(status.stdout, /^wildcard-perms open threads \[claude\]: OFF, 1 thread, INDEX line \(compiled, not installed\) \(/m);
  assert.match(status.stdout, /^wildcard-perms open threads \[codex\]: OFF, 1 thread, INDEX line \(compiled, not installed\) \(/m);
  assert.match(status.stdout, /^wildcard-perms open threads: INDEX MEMORY\.md is 141 lines \(budget 140\): compact it\.$/m);

  const on = s.run(['--open-threads', 'on']);
  assert.equal(on.status, 0, on.stderr);
  assert.match(on.stdout, /^wildcard-perms open threads \[claude\]: ON, 1 thread, INDEX line — /m);
  assert.match(on.stdout, /^wildcard-perms open threads \[codex\]: ON, 1 thread, INDEX line — /m);
  assert.ok(s.claude().startsWith('# Mine\n') && s.claude().includes(BEGIN));
  assert.ok(s.codex().includes(BEGIN));
  assert.match(s.run(['--open-threads', 'status']).stdout, /\[claude\]: ON, 1 thread, INDEX line \(/);
  assert.match(s.run(['--open-threads', 'on']).stdout, /\[claude\]: ON, 1 thread, INDEX line \(already\) — /);

  const off = s.run(['--open-threads', 'off']);
  assert.equal(off.status, 0, off.stderr);
  assert.match(off.stdout, /\[claude\]: OFF — /);
  assert.equal(s.claude(), '# Mine\n', 'off is a byte-for-byte round trip');
  assert.equal(s.codex(), '# Codex mine\n');
  assert.deepEqual(s.calls(), [], 'status, on and off never run recall.py');
});

test('on with nothing compiled says so, exits 1, and writes nothing', (t) => {
  const s = setup(t);
  assert.match(s.run(['--open-threads', 'status']).stdout, /\[claude\]: OFF \(nothing compiled\) \(/);
  const on = s.run(['--open-threads', 'on']);
  assert.equal(on.status, 1);
  assert.match(on.stderr, /^wildcard-perms --open-threads on: nothing compiled yet at .*open-threads\.generated\.md: `wildcard-perms --open-threads refresh` compiles and installs$/m);
  assert.equal(s.claude(), '# Mine\n');
  assert.equal(fs.existsSync(path.join(s.home, '.claude', 'backups')), false);
});

test('refresh compiles with --threads-compile, installs, and is quiet and exit-0 when nothing changed', (t) => {
  const s = setup(t);
  const first = s.run(['--open-threads', 'refresh']);
  assert.equal(first.status, 0, first.stderr);
  assert.deepEqual(s.calls(), [['--threads-compile']], 'one compile, with the threads flag');
  assert.match(first.stdout, /\[claude\]: ON, 2 threads — /);
  assert.ok(s.claude().includes('- **AWAITING** Second. (b)'));
  const second = s.run(['--open-threads', 'refresh']);
  assert.equal(second.status, 0, second.stderr);
  assert.equal(second.stdout, '', 'an unchanged refresh prints nothing');
  // The last thread closes: the next refresh removes the block from every agent.
  fs.writeFileSync(s.fixture, NONE);
  const closed = s.run(['--open-threads', 'refresh']);
  assert.equal(closed.status, 0, closed.stderr);
  assert.match(closed.stdout, /\[claude\]: OFF, nothing open and MEMORY\.md within its budgets — /);
  assert.equal(s.claude(), '# Mine\n');
  assert.equal(s.codex(), '# Codex mine\n');
  // MUTATION: run `--gates-compile` in openThreads' refresh and the call log fails; print every
  // refresh row and the quiet assertion fails.
});

test('refresh says what happened when the compile fails, and passes a warning through', (t) => {
  const s = setup(t);
  const nothing = s.run(['--open-threads', 'refresh'], { ACOLYTE_STUB_MODE: 'fail' });
  assert.equal(nothing.status, 1);
  assert.match(nothing.stderr, /^wildcard-perms --open-threads refresh: compile failed, and nothing was installed \(\[recall\] refusing to compile open threads: the stub was told to\)$/m);
  assert.equal(s.claude(), '# Mine\n');

  assert.equal(s.run(['--open-threads', 'refresh']).status, 0, 'precondition: a compile is installed');
  const stale = s.run(['--open-threads', 'refresh'], { ACOLYTE_STUB_MODE: 'fail' });
  assert.equal(stale.status, 0, stale.stderr);
  assert.match(stale.stderr, /compile failed, installing whatever was last compiled \(\[recall\] refusing/);

  fs.writeFileSync(s.fixture, compiled({ threads: ['- **OPEN** Only one now. (a)'] }));
  const warned = s.run(['--open-threads', 'refresh'], { ACOLYTE_STUB_MODE: 'warn' });
  assert.equal(warned.status, 0, warned.stderr);
  assert.match(warned.stderr, /^\[recall\] open thread left out: c\.md: unknown status 'wip'$/m, 'the compile\'s warning is passed through');
  assert.match(warned.stdout, /\[claude\]: ON, 1 thread — /);
});

test('refresh over a torn compile refuses, writes nothing, and does not advise itself', (t) => {
  const s = setup(t);
  fs.writeFileSync(s.fixture, TWO.replace('First', 'Edited'));
  const torn = s.run(['--open-threads', 'refresh']);
  assert.equal(torn.status, 1);
  assert.match(torn.stderr, /^wildcard-perms --open-threads refresh: .*open-threads\.generated\.md does not match the sha in its own header .*: nothing was written; the next refresh tries again$/m);
  assert.doesNotMatch(torn.stderr, /recompile with/, 'refresh never tells a hook to run refresh');
  assert.equal(s.claude(), '# Mine\n');
  assert.equal(s.codex(), '# Codex mine\n');
});

test('refresh never writes a held CLAUDE.md in place; on still does', (t) => {
  const s = setup(t, { compiledText: TWO });
  const file = path.join(s.home, '.claude', 'CLAUDE.md');
  const hold = path.join(s.home, 'hold.js');
  fs.writeFileSync(hold, `const fs = require('fs'), path = require('path');
const real = fs.renameSync;
fs.renameSync = function (from, to) {
  if (path.resolve(String(to)) === path.resolve(${JSON.stringify(file)})) {
    throw Object.assign(new Error('EPERM: operation not permitted, rename'), { code: 'EPERM' });
  }
  return real.apply(this, arguments);
};
process.emitWarning = () => {};
require(${JSON.stringify(STUB)});
`);
  const refresh = s.run(['--open-threads', 'refresh'], {}, hold);
  assert.equal(refresh.status, 1);
  assert.match(refresh.stderr, /^wildcard-perms --open-threads \[claude\]: .*rename attempts/m);
  assert.equal(s.claude(), '# Mine\n', 'the held CLAUDE.md keeps every byte');
  assert.ok(s.codex().includes(BEGIN), 'and Codex, which is not held, is installed');
  const on = s.run(['--open-threads', 'on'], {}, hold);
  assert.equal(on.status, 0, on.stderr);
  assert.ok(s.claude().includes(BEGIN), 'a person\'s `on` keeps the in-place fallback');
  // MUTATION: pass `inPlaceFallback: true` for refresh in openThreads and the first assertion on
  // CLAUDE.md fails.
});

test('a bad sub-verb prints the usage and exits 1', (t) => {
  const s = setup(t);
  const bad = s.run(['--open-threads', 'bogus']);
  assert.equal(bad.status, 1);
  assert.equal(bad.stderr, 'usage: wildcard-perms --open-threads on|off|status|refresh\n');
});

// A second verb (`on --gates off`) is the dispatch chain's one-verb refusal, exit 2
// (test/cli-gates.test.js); the stray words here are openThreads' own.
// MUTATION: drop `extra` from the usage check in openThreads and `on --verbose` installs.
test('an extra argument prints the usage, exits 1 and writes nothing', (t) => {
  const s = setup(t);
  const before = s.claude();
  for (const args of [['--open-threads', 'on', '--verbose'], ['--open-threads', 'refresh', 'extra']]) {
    const bad = s.run(args);
    assert.equal(bad.status, 1, `${args.join(' ')}: ${bad.stdout}${bad.stderr}`);
    assert.equal(bad.stderr, 'usage: wildcard-perms --open-threads on|off|status|refresh\n', args.join(' '));
    assert.equal(s.claude(), before, `${args.join(' ')} wrote CLAUDE.md`);
  }
});
